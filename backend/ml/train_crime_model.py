"""
Train + evaluate the crime-hotspot Random Forest (paper Section IV-B) with a proper
held-out split, then refit on all data and save backend/crime_rf_model.joblib.

NOTE: training data comes from crime_model.generate_training_data(), which is SYNTHETIC
data calibrated to the paper's Pune statistics - not real police records. The metrics
therefore measure how well the RF recovers that synthetic risk function.

Usage: python backend/ml/train_crime_model.py
"""

import datetime
import json
import os
import sys

import joblib
import numpy as np
from sklearn.ensemble import RandomForestClassifier
from sklearn.metrics import (accuracy_score, classification_report, confusion_matrix, f1_score,
                             roc_auc_score)
from sklearn.model_selection import train_test_split

HERE = os.path.dirname(os.path.abspath(__file__))
BACKEND = os.path.dirname(HERE)
if BACKEND not in sys.path:
    sys.path.insert(0, BACKEND)

from crime_model import FEATURES, MODEL_FILE, generate_training_data  # noqa: E402

REPORT_DIR = os.path.join(HERE, "reports")
CLASS_NAMES = ["Low Risk", "Medium Risk", "High Risk"]
RF_PARAMS = dict(n_estimators=100, max_depth=12, min_samples_split=4, random_state=42, class_weight="balanced")


def main():
    X, y, _ = generate_training_data()
    X_tr, X_te, y_tr, y_te = train_test_split(X, y, test_size=0.2, stratify=y, random_state=42)

    rf = RandomForestClassifier(n_jobs=2, **RF_PARAMS)
    rf.fit(X_tr, y_tr)
    proba = rf.predict_proba(X_te)
    pred = proba.argmax(1)

    rep = classification_report(y_te, pred, target_names=CLASS_NAMES, output_dict=True, zero_division=0)
    metrics = {
        "generated_at": datetime.datetime.now(datetime.timezone.utc).isoformat(),
        "data": "synthetic, crime_model.generate_training_data() (calibrated to paper, not real police records)",
        "n_samples": int(len(y)), "n_train": int(len(y_tr)), "n_test": int(len(y_te)),
        "class_distribution": {c: int((y == i).sum()) for i, c in enumerate(CLASS_NAMES)},
        "features": FEATURES,
        "params": RF_PARAMS,
        "accuracy": float(accuracy_score(y_te, pred)),
        "weighted_f1": float(f1_score(y_te, pred, average="weighted")),
        "macro_f1": float(f1_score(y_te, pred, average="macro")),
        "macro_auc_roc_ovr": float(roc_auc_score(y_te, proba, multi_class="ovr", average="macro")),
        "per_class": {c: {k: float(rep[c][k]) for k in ("precision", "recall", "f1-score", "support")}
                      for c in CLASS_NAMES},
        "confusion_matrix": confusion_matrix(y_te, pred).tolist(),
        "feature_importances": {f: float(v) for f, v in zip(FEATURES, rf.feature_importances_)},
        "paper_reported": {"weighted_f1": 0.92, "auc_roc": 0.96},
    }

    os.makedirs(REPORT_DIR, exist_ok=True)
    with open(os.path.join(REPORT_DIR, "crime_rf_metrics.json"), "w") as f:
        json.dump(metrics, f, indent=2)

    L = ["# Crime Hotspot Random Forest - Evaluation Report\n",
         f"Generated: {metrics['generated_at']}\n",
         "> **Honesty note:** the dataset is synthetic (generated by `crime_model.generate_training_data`, "
         "calibrated to the paper's Pune hotspot description), not real police/FIR records. These metrics show "
         "how well the RF recovers that synthetic risk function on a held-out 20% split.\n",
         f"- Samples: {metrics['n_samples']} (train {metrics['n_train']}, test {metrics['n_test']}, stratified 80/20)",
         f"- Class distribution: {metrics['class_distribution']}",
         f"- RandomForest params: {RF_PARAMS}\n",
         "| metric | value | paper |", "|---|---|---|",
         f"| accuracy | {metrics['accuracy']:.4f} | - |",
         f"| weighted F1 | {metrics['weighted_f1']:.4f} | 0.92 |",
         f"| macro F1 | {metrics['macro_f1']:.4f} | - |",
         f"| macro AUC-ROC (OvR) | {metrics['macro_auc_roc_ovr']:.4f} | 0.96 |\n",
         "| class | precision | recall | F1 | support |", "|---|---|---|---|---|"]
    for c, v in metrics["per_class"].items():
        L.append(f"| {c} | {v['precision']:.3f} | {v['recall']:.3f} | {v['f1-score']:.3f} | {int(v['support'])} |")
    L.append("\nConfusion matrix (rows true, cols predicted: Low, Medium, High):\n```")
    for c, row in zip(CLASS_NAMES, metrics["confusion_matrix"]):
        L.append(f"{c:>12s} " + " ".join(f"{v:5d}" for v in row))
    L.append("```\n\nFeature importances:\n")
    for f_, v in sorted(metrics["feature_importances"].items(), key=lambda kv: -kv[1]):
        L.append(f"- {f_}: {v:.3f}")
    L.append(f"\nThe deployed model (`backend/crime_rf_model.joblib`) is refit on all {metrics['n_samples']} samples.")
    with open(os.path.join(REPORT_DIR, "crime_rf_report.md"), "w", encoding="utf-8") as f:
        f.write("\n".join(L))

    final = RandomForestClassifier(**RF_PARAMS)  # n_jobs default (1) as in crime_model.py
    final.fit(X, y)
    joblib.dump(final, MODEL_FILE, compress=3)
    print(json.dumps({k: metrics[k] for k in ("accuracy", "weighted_f1", "macro_auc_roc_ovr")}, indent=1))
    print("saved", MODEL_FILE, os.path.getsize(MODEL_FILE), "bytes")


if __name__ == "__main__":
    main()
